#!/usr/bin/env python3
"""Give a part the 3D model it is missing — only where the model is measured to sit on its pads.

A part has 3D when its zip holds the file its footprint's `(model …)` names
(`sync_3d_models.py`, the app's `ResolveModelPath`). The 2026-10-13 audit
counted 4,720 of 12,572 parts without one: 2,733 footprints name a model
kicad-packages3D does not have (KiCad 10 ships 7,251 STEP files, and its own
footprints name thousands more), 1,485 name none at all — every LCSC part among
them — and the rest carry a file nobody points at.

Sources, each producing CANDIDATES, never answers:

  generator  KiCad's own generator (kicad-library-tools, CadQuery), run for the
             declared names it can build (`--generated DIR`): the model KiCad
             would ship, from the data the footprint was generated from. Placed
             exactly as the footprint already says. CC-BY-SA-4.0 WITH
             KiCad-Libraries-exception, like the rest of kicad-packages3D.
  easyeda    the model EasyEDA attaches to an LCSC part's footprint — the same
             drawing our footprint was decoded from — placed as EasyEDA places
             it: c_rotation (negated: KiCad turns a model by -rz, measured on
             XC6206, whose lone pin only lands with -90), the box centred on
             c_origin, the base at z. The JLCEDA/EasyEDA library terms claim
             these models; a PUBLIC release carrying them needs the owner's
             decision, so every one is marked `origin: easyeda` and `--drop
             easyeda` takes them all out again.

A candidate is accepted only when `model_fit` says its feet are on the pads:
every copper pad (90 %) has a model point on it at the seating plane (SMD) or
in its hole's column (THT), and for SMD at most 35 % of the seating-plane
points land on bare board (KiCad's own SMD models reach 75 %, a standoff's ring;
a model turned the wrong way is near 100 % with its pads bare). The board plane
is z = 0 (|z| <= 0.15 mm), falling back to the lowest point above the board.
Calibrated on 397 of KiCad's own placed models: all 397 pass; a model turned
180 degrees leaves a SOT-23's lone pad bare and fails.
Where both candidate orientations pass (a symmetric part) the first is kept.

Writes the zip (model under the name the footprint declares; for EasyEDA a
`(model …)` line is added), part.json's `model3d` with origin, licence and the
measurement, the shard entry (`has_3d`, `hash`), lib_search.sqlite and the
manifest's `with_3d`, and collections/3d/fill_report.json with every decision.

    python3 tools/fill_3d_models.py --generated /tmp/gen3d --plan
    python3 tools/fill_3d_models.py --generated /tmp/gen3d
    python3 tools/fill_3d_models.py --drop easyeda      # undo one source

The part_bundles must be rebuilt (publish's ensure_part_bundles) before a
release; nothing here uploads anything.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import sqlite3
import zipfile
from collections import Counter
from pathlib import Path

import audit_parts as audit
import model_fit as fit

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'Dist_Repo/v2'
CACHE = Path.home() / '.wireframe/library_cache'
LCSC_SOURCE = ROOT / 'sources/lcsc-parts/kicad'
REPORT = ROOT / 'collections/3d/fill_report.json'
UNIT = 0.254          # one EasyEDA unit in mm

LICENCE = {
    'generator': 'CC-BY-SA-4.0 WITH KiCad-Libraries-exception (generated by KiCad kicad-library-tools)',
    'easyeda': 'JLCEDA/EasyEDA official library terms - confirm before a public release',
}
MIN_COVERAGE = 0.9
MAX_STRAY = 0.8


def accept(placed, pads) -> tuple[bool, dict]:
    cov, bare = fit.coverage(placed, pads)
    smd = all(p['type'] == 'smd' for p in pads if p['number'] and p['type'] != 'np_thru_hole')
    off = fit.stray(placed, pads) if smd else None
    e = fit.extent(placed)
    measure = {'coverage': None if cov is None else round(cov, 3), 'stray': None if off is None else round(off, 3),
               'bare_pads': bare[:12], 'box_mm': [round(v, 2) for v in e] if e else None}
    ok = cov is not None and cov >= MIN_COVERAGE and (off is None or off <= MAX_STRAY) and e and e[5] > 0.05
    return bool(ok), measure


# ------------------------------------------------------------------ sources
def generator_candidates(fp: dict, generated: dict[str, Path]):
    for m in fp['models']:
        stem = os.path.splitext(os.path.basename(m['path']))[0]
        if stem in generated:
            name = stem + '.step'
            yield {'origin': 'generator', 'file': name, 'data': generated[stem].read_bytes(),
                   'offset': [v * 25.4 for v in m['offset']] if m.get('offset_is_at') else m['offset'],
                   'rotate': m['rotate'], 'scale': m['scale'], 'declare': None,
                   'upstream': f'kicad-library-tools generator: {name}'}


def lcsc_ids() -> dict[str, str]:
    """footprint name -> LCSC code, from the collector's provenance files."""
    out = {}
    for f in LCSC_SOURCE.glob('*.lcsc.json'):
        m = json.loads(f.read_text())
        out[m['footprint']] = m['lcsc']
    return out


def easyeda_candidates(fp: dict, lcsc: str):
    path = CACHE / 'easyeda' / f'{lcsc}.json'
    if not path.exists():
        return
    result = json.loads(path.read_text()).get('result') or {}
    pkg = ((result.get('packageDetail') or {}).get('dataStr') or {})
    head = pkg.get('head') or {}
    for shape in pkg.get('shape') or []:
        if not isinstance(shape, str) or not shape.startswith('SVGNODE~'):
            continue
        node = json.loads(shape.split('~', 1)[1])
        attrs = node.get('attrs') or {}
        if attrs.get('c_etype') != 'outline3D' or not attrs.get('uuid'):
            continue
        step = CACHE / 'easyeda3d' / f"{attrs['uuid']}.step"
        if not step.exists():
            return
        data = step.read_bytes()
        points = fit.model_points(data, '.step')
        if not points:
            return
        rx, ry, rz = (float(v) for v in (attrs.get('c_rotation') or '0,0,0').split(','))
        hx, hy = float(head.get('x', 0)), float(head.get('y', 0))
        ox, oy = (float(v) for v in (attrs.get('c_origin') or f'{hx},{hy}').split(','))
        # Where EasyEDA DRAWS the model: the node's own outline, projected onto
        # the canvas. c_origin can be stale — C83939's (MMBT2222A) says
        # (608, -320) on a footprint at (4000, 3000), left behind when the
        # drawing was moved — and its outline is still centred on the pads.
        xs, ys = [], []
        for child in node.get('childNodes') or []:
            values = [float(v) for v in re.findall(r'-?\d+(?:\.\d+)?', (child.get('attrs') or {}).get('points', ''))]
            xs += values[0::2]
            ys += values[1::2]
        anchors = []
        if xs and ys:
            anchors.append(((min(xs) + max(xs)) / 2, (min(ys) + max(ys)) / 2))
        if not anchors or abs(anchors[0][0] - ox) + abs(anchors[0][1] - oy) > 0.5:
            anchors.append((ox, oy))
        base = float(attrs.get('z') or 0) * UNIT
        name = f"{fp['name']}.step"
        # Two placements, because EasyEDA's STEP files follow two: most are
        # placed by their box centred on the anchor, some by their own origin
        # AT c_origin (measured on 717 LCSC parts: 451 fit the first, 431 the
        # second, 505 either). The sign second: -1 is EasyEDA's convention (23
        # asymmetric parts fit only with it, 2 only without), and on a
        # symmetric land with a polarity — a diode, a tantalum — the wrong sign
        # still fits, 180 degrees out. The fit decides, part by part.
        for sign in (-1, 1):
            rot = [sign * rx, sign * ry, sign * rz]
            e = fit.extent(fit.place(points, (0, 0, 0), rot))
            placements = [('box', [(ax - hx) * UNIT - (e[0] + e[3]) / 2, -((ay - hy) * UNIT - (e[1] + e[4]) / 2),
                                   base - e[2]]) for ax, ay in anchors]
            placements.append(('origin', [(ox - hx) * UNIT, -(oy - hy) * UNIT, base]))
            for convention, offset in placements:
                yield {'origin': 'easyeda', 'file': name, 'data': data, 'offset': offset, 'rotate': rot,
                       'scale': [1, 1, 1], 'declare': f'${{KIPRJMOD}}/{name}', 'points': points,
                       'placement': convention,
                       'upstream': f"easyeda 3D {attrs['uuid']} ({attrs.get('title', '')}) for LCSC {lcsc}"}
        return


# ------------------------------------------------------------------ writing
def model_line(c) -> str:
    def number(x: float) -> str:
        text = f'{x:.4f}'.rstrip('0').rstrip('.')
        return '0' if text in ('', '-0') else text

    def xyz(v):
        return ' '.join(number(x) for x in v)
    return (f'  (model "{c["declare"]}"\n    (offset (xyz {xyz(c["offset"])}))\n'
            f'    (scale (xyz {xyz(c["scale"])}))\n    (rotate (xyz {xyz(c["rotate"])}))\n  )\n')


def rewrite(path: Path, fp_member: str, fp_text: str, c: dict, measure: dict) -> None:
    if c['declare']:
        # A footprint that names a model the zip will not carry is replaced
        # wholesale; one that names none gets the line before its last paren.
        fp_text = re.sub(r'\n\s*\(model\s[^\n]*(?:\n\s+\([^\n]*)*\n\s*\)', '', fp_text)
        end = fp_text.rstrip().rfind(')')
        fp_text = fp_text[:end] + model_line(c) + fp_text[end:]
    tmp = path.with_suffix('.zip.tmp')
    with zipfile.ZipFile(path) as src, zipfile.ZipFile(tmp, 'w', zipfile.ZIP_DEFLATED) as dst:
        for info in src.infolist():
            if info.filename.lower() == c['file'].lower():
                continue
            data = src.read(info.filename)
            if info.filename == fp_member:
                data = fp_text.encode()
            elif info.filename == 'part.json':
                m = json.loads(data)
                m['model3d'] = {'file': c['file'], 'format': 'step', 'origin': c['origin'],
                                'resolved_by': 'declared_by_footprint' if not c['declare'] else 'placed_from_source',
                                'upstream': c['upstream'], 'license': LICENCE[c['origin']], 'fit': measure}
                data = json.dumps(m, ensure_ascii=False, indent=1).encode()
            dst.writestr(info, data)
        dst.writestr(c['file'], c['data'])
    tmp.replace(path)


def drop(path: Path, origin: str) -> bool:
    """Take out a model this tool added from `origin`, and its (model) line."""
    with zipfile.ZipFile(path) as z:
        m = json.loads(z.read('part.json'))
        model = m.get('model3d') or {}
        if model.get('origin') != origin:
            return False
        fp_member = next(n for n in z.namelist() if n.endswith('.kicad_mod'))
        fp_text = z.read(fp_member).decode('utf-8', 'replace')
        if model.get('resolved_by') == 'placed_from_source':
            fp_text = re.sub(r'\n\s*\(model\s[^\n]*(?:\n\s+\([^\n]*)*\n\s*\)', '', fp_text) + '\n'
        tmp = path.with_suffix('.zip.tmp')
        with zipfile.ZipFile(tmp, 'w', zipfile.ZIP_DEFLATED) as dst:
            for info in z.infolist():
                if info.filename == model.get('file'):
                    continue
                data = z.read(info.filename)
                if info.filename == fp_member:
                    data = fp_text.encode()
                elif info.filename == 'part.json':
                    m.pop('model3d', None)
                    data = json.dumps(m, ensure_ascii=False, indent=1).encode()
                dst.writestr(info, data)
    tmp.replace(path)
    return True


def save_indexes(shards: dict, changed: dict[str, bool]) -> None:
    for shard_path, shard in shards.items():
        shard_path.write_text(json.dumps(shard, ensure_ascii=False, indent=2))
    with sqlite3.connect(OUT / 'lib_search.sqlite') as conn:
        conn.executemany('UPDATE part SET has_3d=? WHERE id=?', [(int(v), k) for k, v in changed.items()])
    manifest_path = OUT / 'lib_index.json'
    manifest = json.loads(manifest_path.read_text())
    visible = [e for s in shards.values() for e in s['entries'] if e.get('tier') in {'A', 'B', 'G'}]
    manifest.setdefault('counts', {})['with_3d'] = sum(bool(e.get('has_3d')) for e in visible)
    manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n')


def fix_offsets(shards: dict, plan: bool) -> dict[str, bool]:
    """A model the footprint names and the zip carries, whose feet land on no
    pad — while the SAME model at the SAME rotation with no offset does. Upstream
    typed the offset wrong: JLCPCB's NZT605 and PT7C4372 put theirs ~1 m away
    (-941.76, 660.4 mm), SparkFun's 1x01 header 2.5 mm off its pin. Only the
    offset is changed; a model that needs a different ROTATION is listed, not
    turned — which way a connector faces is not something a pad count can say."""
    changed, listed = {}, []
    for shard in shards.values():
        for e in shard['entries']:
            path = OUT / 'parts' / f"{e.get('slug', '')}.zip"
            if not path.exists():
                continue
            with zipfile.ZipFile(path) as z:
                names = z.namelist()
                fp_member = next((n for n in names if n.endswith('.kicad_mod')), '')
                if not fp_member:
                    continue
                fp_text = z.read(fp_member).decode('utf-8', 'replace')
                fp = audit.read_footprint(fp_text)
                hit = next(((m, audit.resolve_model(names, m['path'])[0]) for m in fp['models']
                            if m['path'] and audit.resolve_model(names, m['path'])[0]), None)
                if not hit or not fp['pads']:
                    continue
                m, member = hit
                points = fit.model_points(z.read(member), os.path.splitext(member)[1].lower())
            if not points:
                continue
            offset = [v * 25.4 for v in m['offset']] if m.get('offset_is_at') else m['offset']
            ok, _ = accept(fit.place(points, offset, m['rotate'], m['scale']), fp['pads'])
            if ok:
                continue
            cov, _ = fit.coverage(fit.place(points, offset, m['rotate'], m['scale']), fp['pads'])
            if cov is not None and cov >= 0.6:
                continue                      # the audit's own threshold: not misplaced
            zero = [0.0, 0.0, offset[2]]
            ok, measure = accept(fit.place(points, zero, m['rotate'], m['scale']), fp['pads'])
            if not ok:
                listed.append({'id': e['id'], 'model': member, 'coverage': cov})
                continue
            changed[e['id']] = True
            listed.append({'id': e['id'], 'model': member, 'offset_was': offset, 'fixed': True, **measure})
            if plan:
                continue
            block = re.compile(r'(\(model\s+"?' + re.escape(m['path']) + r'"?.*?\((?:offset|at)\s*\(xyz\s+)'
                               r'[-\d.eE+]+\s+[-\d.eE+]+(\s+[-\d.eE+]+\s*\))', re.S)
            fp_text, n = block.subn(lambda g: g.group(1) + '0 0' + g.group(2), fp_text, count=1)
            if n != 1:
                changed.pop(e['id'], None)
                listed[-1].pop('fixed', None)
                listed[-1]['why'] = 'offset not found in the footprint text'
                continue
            tmp = path.with_suffix('.zip.tmp')
            with zipfile.ZipFile(path) as src, zipfile.ZipFile(tmp, 'w', zipfile.ZIP_DEFLATED) as dst:
                for info in src.infolist():
                    data = src.read(info.filename)
                    if info.filename == fp_member:
                        data = fp_text.encode()
                    elif info.filename == 'part.json':
                        mj = json.loads(data)
                        if isinstance(mj.get('model3d'), dict):
                            mj['model3d']['offset_repaired'] = {'was_mm': offset, 'fit': measure}
                        data = json.dumps(mj, ensure_ascii=False, indent=1).encode()
                    dst.writestr(info, data)
            tmp.replace(path)
            e['hash'] = hashlib.sha256(path.read_bytes()).hexdigest()
    report = ROOT / 'collections/3d/offsets.json'
    if not plan:
        report.write_text(json.dumps({'schema': 1, 'parts': listed}, ensure_ascii=False, indent=1) + '\n')
    print(f"offsets repaired: {sum(1 for x in listed if x.get('fixed'))}; "
          f"misplaced and left for a person (rotation): {sum(1 for x in listed if not x.get('fixed'))}")
    return changed


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--generated', type=Path, help='STEP files built by KiCad\'s generator (any depth)')
    # easyeda is withdrawn (EasyEDA's terms forbid redistributing its models; add_lcsc_parts.py): only
    # --drop easyeda still has a use, on a tree built before 2026-11-03.
    ap.add_argument('--sources', default='generator', help='comma-separated, in order of preference')
    ap.add_argument('--only', default='', help='substring of part ids to consider')
    ap.add_argument('--plan', action='store_true', help='measure and report; write nothing')
    ap.add_argument('--drop', metavar='ORIGIN', help='remove every model this tool added from ORIGIN, and stop')
    ap.add_argument('--fix-offsets', action='store_true',
                    help='re-seat models whose declared offset puts them off their pads, and stop')
    args = ap.parse_args()

    shards = {f: json.loads(f.read_text()) for f in sorted((OUT / 'shards').glob('*.json'))}
    changed: dict[str, bool] = {}
    if args.drop:
        n = 0
        for shard in shards.values():
            for e in shard['entries']:
                path = OUT / 'parts' / f"{e.get('slug', '')}.zip"
                if path.exists() and drop(path, args.drop):
                    e['has_3d'] = False
                    e['hash'] = hashlib.sha256(path.read_bytes()).hexdigest()
                    changed[e['id']] = False
                    n += 1
        save_indexes(shards, changed)
        print(f'dropped {n} models from {args.drop}')
        return

    if args.fix_offsets:
        fixed = fix_offsets(shards, args.plan)
        if not args.plan:
            for shard_path, shard in shards.items():
                shard_path.write_text(json.dumps(shard, ensure_ascii=False, indent=2))
        return

    sources = [s for s in args.sources.split(',') if s]
    generated = {}
    if args.generated:
        generated = {p.stem: p for p in args.generated.rglob('*.step')}
    footprint_lcsc = lcsc_ids() if 'easyeda' in sources else {}

    decisions, outcome = [], Counter()
    for shard_path, shard in shards.items():
        for e in shard['entries']:
            if args.only and args.only not in e.get('id', ''):
                continue
            path = OUT / 'parts' / f"{e.get('slug', '')}.zip"
            if not path.exists():
                continue
            with zipfile.ZipFile(path) as z:
                names = z.namelist()
                fp_member = next((n for n in names if n.endswith('.kicad_mod')), '')
                if not fp_member:
                    continue
                fp_text = z.read(fp_member).decode('utf-8', 'replace')
                fp = audit.read_footprint(fp_text)
                if any(audit.resolve_model(names, m['path'])[0] for m in fp['models'] if m['path']):
                    continue                        # has the model its footprint names
            if not fp['pads']:
                continue
            tried = []
            chosen = None
            for source in sources:
                if source == 'generator' and generated:
                    cands = list(generator_candidates(fp, generated))
                elif source == 'easyeda' and e.get('source') == 'wireframe-lcsc-parts':
                    lcsc = footprint_lcsc.get(fp['name'])
                    cands = list(easyeda_candidates(fp, lcsc)) if lcsc else []
                else:
                    cands = []
                for c in cands:
                    points = c.get('points') or fit.model_points(c['data'], '.step')
                    ok, measure = accept(fit.place(points, c['offset'], c['rotate'], c['scale']), fp['pads'])
                    tried.append({'origin': c['origin'], 'rotate': c['rotate'], **measure, 'accepted': ok})
                    if ok:
                        chosen = (c, measure)
                        break
                if chosen:
                    break
            if not tried:
                outcome['no_candidate'] += 1
                continue
            decision = {'id': e['id'], 'footprint': fp['name'], 'tried': tried}
            if chosen:
                c, measure = chosen
                outcome[f"added_{c['origin']}"] += 1
                decision['added'] = {'origin': c['origin'], 'file': c['file'], 'upstream': c['upstream']}
                if not args.plan:
                    rewrite(path, fp_member, fp_text, c, measure)
                    e['has_3d'] = True
                    e['hash'] = hashlib.sha256(path.read_bytes()).hexdigest()
                    changed[e['id']] = True
            else:
                outcome['rejected_by_fit'] += 1
            decisions.append(decision)

    print(json.dumps(dict(outcome), indent=2))
    if args.plan:
        for d in decisions[:40]:
            print(d['id'], '->', d.get('added', {}).get('origin', 'REJECTED'),
                  [(t['origin'], t['rotate'][2], t['coverage'], t['stray']) for t in d['tried']])
        return
    save_indexes(shards, changed)
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    previous = json.loads(REPORT.read_text()).get('decisions', []) if REPORT.exists() else []
    seen = {d['id'] for d in decisions}
    REPORT.write_text(json.dumps({'schema': 1, 'outcome': dict(outcome),
                                  'policy': f'accepted when >= {MIN_COVERAGE:.0%} of copper pads carry a model point '
                                            f'at the seating plane (SMD) or in the hole column (THT), and SMD '
                                            f'stray <= {MAX_STRAY:.0%}',
                                  'decisions': [d for d in previous if d['id'] not in seen] + decisions},
                                 ensure_ascii=False, indent=1) + '\n')


if __name__ == '__main__':
    main()
